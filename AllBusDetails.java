    private void loadBusDetails() {
    javax.swing.table.DefaultTableModel model =
        (javax.swing.table.DefaultTableModel) jTable1.getModel();

    model.setRowCount(0);

    String url = "jdbc:mysql://localhost:3306/busm";
    String user = "root";
    String password = "swapna3264";

    String sql = "SELECT * FROM bus_details";

    try (
        java.sql.Connection con =
            java.sql.DriverManager.getConnection(url, user, password);
        java.sql.Statement st = con.createStatement();
        java.sql.ResultSet rs = st.executeQuery(sql)
    ) {
        while (rs.next()) {
    model.addRow(new Object[]{
        rs.getObject("id"),
        rs.getObject("bus_no"),
        rs.getObject("movement"),
        rs.getObject("bus_source"),
        rs.getObject("bus_dest"),
        rs.getObject("depart_date"),
        rs.getObject("depart_time"),
        rs.getObject("price"),
        rs.getObject("total_seat")
            });
        }
    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this, e.getMessage()
        );
    }
}

